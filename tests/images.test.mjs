import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdir, mkdtemp, readFile, readdir } from "node:fs/promises";
import { resolve, join } from "node:path";
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import sharp from "sharp";

test("image preparation preserves originals, orients photos and never enlarges them", async () => {
  const root = resolve(import.meta.dirname, "..");
  await mkdir(join(root, ".cache"), { recursive: true });
  const directory = await mkdtemp(join(root, ".cache", "image-test-"));
  const input = join(directory, "originals");
  const output = join(directory, "web");
  await mkdir(input);
  const fixture = (width, height) => sharp({ create: { width, height, channels: 3, background: "#91a8a1" } });
  await fixture(300, 200).jpeg().toFile(join(input, "small.jpg"));
  await fixture(2600, 1800).jpeg().toFile(join(input, "large.jpg"));
  await fixture(600, 400).withMetadata({ orientation: 6 }).jpeg().toFile(join(input, "rotated.jpg"));
  const hash = async file => createHash("sha256").update(await readFile(file)).digest("hex");
  const originals = await Promise.all((await readdir(input)).map(async name => [name, await hash(join(input, name))]));
  const result = spawnSync(process.execPath, ["tools/prepare-images.mjs", "--input", input, "--output", output], { cwd: root, encoding: "utf8" });
  assert.equal(result.status, 0, result.stderr);
  const manifest = JSON.parse(await readFile(join(output, "image-manifest.json"), "utf8"));
  const small = manifest.find(record => record.src.includes("small"));
  assert.deepEqual(small.variants.map(variant => variant.width), [300]);
  const large = manifest.find(record => record.src.includes("large"));
  assert.deepEqual(large.variants.map(variant => variant.width), [480, 960, 1600, 2400]);
  const rotated = manifest.find(record => record.src.includes("rotated"));
  const rotatedMetadata = await sharp(join(root, rotated.src)).metadata();
  assert.equal(rotated.width, 400);
  assert.equal(rotated.height, 600);
  assert.equal(rotatedMetadata.width, 400);
  assert.equal(rotatedMetadata.height, 600);
  assert.equal(rotatedMetadata.exif, undefined);
  for (const [name, originalHash] of originals) assert.equal(await hash(join(input, name)), originalHash);
  const invalid = spawnSync(process.execPath, ["tools/prepare-images.mjs", "--input", input, "--output", input], { cwd: root, encoding: "utf8" });
  assert.notEqual(invalid.status, 0);
  for (const [name, originalHash] of originals) assert.equal(await hash(join(input, name)), originalHash);
});
